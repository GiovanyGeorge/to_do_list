import React from "react";
import clsx from "clsx";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  variant?: "default" | "elevated" | "interactive";
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = "default", ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={clsx(
          "rounded-2xl border border-border-subtle transition-all duration-200",
          variant === "default" && "bg-background-card",
          variant === "elevated" && "bg-background-elevated shadow-md",
          variant === "interactive" &&
            "bg-background-card hover:border-accent/40 hover:bg-background-card/90 cursor-pointer shadow-sm",
          className
        )}
        {...props}
      />
    );
  }
);
Card.displayName = "Card";

